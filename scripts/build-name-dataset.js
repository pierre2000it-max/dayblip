// Builds src/data/name-popularity.ts from public/data/names.json (US SSA, 1880-2025).
// Run: node scripts/build-name-dataset.js
const fs = require("fs");
const names = require("../public/data/names.json");
const decades = [];
for (let d = 1880; d <= 2020; d += 10) decades.push(d);
const rows = [];
for (const d of decades) {
  const end = Math.min(d + 9, 2025);
  for (const sex of ["F", "M"]) {
    const totals = [];
    for (const name of Object.keys(names)) {
      const byYear = names[name][sex];
      if (!byYear) continue;
      let sum = 0;
      for (let y = d; y <= end; y++) sum += byYear[y] || 0;
      if (sum > 0) totals.push([name, sum]);
    }
    totals.sort((a, b) => b[1] - a[1]);
    totals.slice(0, 10).forEach(([name, sum], i) => {
      rows.push([`${d}s`, sex === "F" ? "Girls" : "Boys", i + 1, name, sum]);
    });
  }
}
const out =
  "// Generated by scripts/build-name-dataset.js from public/data/names.json (US SSA). Do not edit by hand.\n" +
  "// Columns: decade, sex, rank, name, births in decade (2020s covers 2020-2025 only).\n" +
  "export const NAME_ROWS: Array<[string, string, number, string, number]> = " +
  JSON.stringify(rows) + ";\n";
fs.writeFileSync("src/data/name-popularity.ts", out);
console.log(rows.length, "rows");
